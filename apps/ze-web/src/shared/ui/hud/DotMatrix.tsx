interface Props {
  text: string;
  /** Dot pitch in px. */
  size?: number;
  color?: string;
  /** Unlit dots drawn faintly, like a real matrix. */
  ghost?: boolean;
  className?: string;
  title?: string;
}

export function DotMatrix({ text, size = 4, color = "var(--cream)", ghost = true, className, title }: Props) {
  const chars = text.toUpperCase().split("");
  const pitch = size;
  const gap = 1; // columns between glyphs
  const w = chars.length * (5 + gap) * pitch - gap * pitch;
  const h = 7 * pitch;
  const r = pitch * 0.34;
  const lit: string[] = [];
  const dim: string[] = [];
  chars.forEach((ch, ci) => {
    const g = G[ch] ?? G["?"];
    for (let y = 0; y < 7; y++) {
      for (let x = 0; x < 5; x++) {
        const cx = (ci * (5 + gap) + x) * pitch + pitch / 2;
        const cy = y * pitch + pitch / 2;
        (g[y][x] === "1" ? lit : dim).push(`M${cx - r},${cy}a${r},${r} 0 1,0 ${r * 2},0a${r},${r} 0 1,0 ${-r * 2},0`);
      }
    }
  });
  return (
    <svg
      className={className}
      width={w}
      height={h}
      viewBox={`0 0 ${w} ${h}`}
      role="img"
      aria-label={title ?? text}
      style={{ display: "block", maxWidth: "100%", height: "auto" }}
    >
      {ghost && <path d={dim.join("")} fill={color} opacity={0.12} />}
      <path d={lit.join("")} fill={color} />
    </svg>
  );
}
